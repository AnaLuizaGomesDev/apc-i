#include <stdio.h>

int main(){
    // == igualdade
    // != diferença
    // < menor
    // <= menor ou igual
    // > maior
    // >= maior ou igual
    // 1 é VERDADEIRO, 0 é FALSO

    printf("2 == 5? %i\n", 2 == 5);
    printf("2 != 5? %i\n", 2 != 5);
    printf("2 < 5? %i\n", 2 < 5);
    printf("2 <= 5? %i\n", 2 <= 5);
    printf("2 > 5? %i\n", 2 > 5);
    printf("2 >= 5? %i\n", 2 >= 5);

    return 0;
}